package com.fitwallet.batch.crawl.dto;

/**
 * 카드 상세 페이지에서 수집하는 원문 영역.
 *
 * <p>카드사마다 페이지 구조는 다르지만 <b>담기는 내용은 이 셋으로 수렴한다</b>고 보고
 * 공통 타입으로 뒀다. 어댑터가 자기 페이지의 어느 영역을 어디에 넣을지 정한다.
 *
 * <p>여기 없는 영역은 수집하지 않는다. 특히 <b>확인사항/유의사항</b>류는 카드당 8천 자가
 * 넘어 페이지에서 가장 큰 영역이지만 내용이 할인 제외매출·연체이자율 같은 법적 고지문이다
 * (KB 카드 3종 실측 8,841 / 8,554 / 8,127자, 카드 간 유사도 52%). 혜택 판정에 쓸 값이
 * 없는 데다, 넣으면 "상품권 구입은 할인 제외" 같은 문장이 오히려 혜택으로 오추출된다.
 *
 * <p>상수 이름은 DDL의 {@code ck_crawl_raw_card_section} CHECK 값과 같아야 한다
 * (AGENTS.md §6 — 커스텀 TypeHandler 없이 기본 {@code EnumTypeHandler}가 변환한다).
 */
public enum SectionType {

    /** 주요혜택. 카드 대표 혜택을 요약한 짧은 영역. */
    SUMMARY,

    /** 상세혜택. 전월실적 구간·한도·업종이 표로 들어 있는 본체. */
    DETAIL,

    /** 연회비. */
    ANNUAL_FEE
}
